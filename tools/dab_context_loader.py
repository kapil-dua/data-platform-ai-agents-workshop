"""
DAB Context Loader
==================
Reads Databricks Asset Bundle (databricks.yml) files generated by setup.py
and returns structured job context for the RCA agent.

The DAB YAML is the authoritative source for what a job is SUPPOSED to do:
  - Source and target tables/paths
  - Upstream system (WMS, Finance system, CRM, etc.)
  - File naming conventions and archive paths
  - SLA and schedule
  - Layer (raw_to_cleansed, cleansed_to_conformed)

Usage:
    loader = DABContextLoader()
    context = loader.get_context("etl_raw_to_cleansed_inventory")
    # Returns dict with all job metadata or {} if not found
"""

from __future__ import annotations

import os
from pathlib import Path
from typing import Any

try:
    import yaml
    _YAML_AVAILABLE = True
except ImportError:
    _YAML_AVAILABLE = False


class DABContextLoader:
    """Loads job context from DAB YAML bundle files."""

    def __init__(self, dab_base_path: str | None = None) -> None:
        """
        Args:
            dab_base_path: Path to the .dab/ directory containing job bundle files.
                           Defaults to .dab/ relative to the project root.
        """
        if dab_base_path:
            self.dab_base = Path(dab_base_path)
        else:
            # Walk up from this file to find the project root (.dab/ sibling of scripts/)
            self.dab_base = Path(__file__).resolve().parent.parent / ".dab"

    def get_context(self, job_name: str) -> dict[str, Any]:
        """
        Load context for a specific job from its DAB YAML file.

        Args:
            job_name: Databricks job name (must match the bundle directory name)

        Returns:
            Dict with structured job context, or empty dict if not found.
        """
        dab_file = self.dab_base / job_name / "databricks.yml"

        if not dab_file.exists():
            return {}

        try:
            return self._parse_dab(dab_file, job_name)
        except Exception as e:
            print(f"[DABContextLoader] Warning: could not parse {dab_file}: {e}")
            return {}

    def get_all_contexts(self) -> dict[str, dict[str, Any]]:
        """Load context for all jobs that have DAB files."""
        contexts: dict[str, dict[str, Any]] = {}
        if not self.dab_base.exists():
            return contexts
        for job_dir in self.dab_base.iterdir():
            if job_dir.is_dir():
                ctx = self.get_context(job_dir.name)
                if ctx:
                    contexts[job_dir.name] = ctx
        return contexts

    def _parse_dab(self, dab_file: Path, job_name: str) -> dict[str, Any]:
        """Parse a databricks.yml file and extract RCA-relevant context."""
        content = dab_file.read_text(encoding="utf-8")

        if _YAML_AVAILABLE:
            raw = yaml.safe_load(content)
            return self._extract_from_parsed(raw, job_name)
        else:
            # Fallback: simple line-by-line key:value parser
            return self._extract_from_text(content, job_name)

    def _extract_from_parsed(self, raw: dict, job_name: str) -> dict[str, Any]:
        """Extract structured context from parsed YAML dict."""
        jobs = raw.get("resources", {}).get("jobs", {})
        job_def = jobs.get(job_name, {})

        tags   = job_def.get("tags", {})
        tasks  = job_def.get("tasks", [])
        params = {}
        if tasks:
            params = tasks[0].get("notebook_task", {}).get("base_parameters", {})

        schedule = job_def.get("schedule", {})

        return {
            "job_name":        job_name,
            "description":     job_def.get("description", ""),
            "layer":           tags.get("layer", ""),
            "upstream_system": tags.get("upstream_system", ""),
            "source_table":    tags.get("source_table", "") or params.get("source_table", ""),
            "target_table":    tags.get("target_table", "") or params.get("target_table", ""),
            "target_schema":   tags.get("target_schema", "") or params.get("target_schema", ""),
            "sla":             tags.get("sla", ""),
            "schedule":        schedule.get("quartz_cron_expression", ""),
            "parameters":      params,
            "source_path":     params.get("source_path", ""),
            "filename_pattern":params.get("filename_pattern", ""),
            "archive_path":    params.get("archive_path", ""),
        }

    def _extract_from_text(self, content: str, job_name: str) -> dict[str, Any]:
        """Fallback parser — extracts key: value lines from YAML text without yaml lib."""
        ctx: dict[str, Any] = {"job_name": job_name, "parameters": {}}
        in_params = False

        for line in content.splitlines():
            stripped = line.strip()
            if not stripped or stripped.startswith("#"):
                continue

            # Detect base_parameters block
            if "base_parameters:" in stripped:
                in_params = True
                continue

            if in_params:
                if line.startswith("        ") or line.startswith("\t\t"):
                    # indented parameter line
                    if ":" in stripped:
                        k, _, v = stripped.partition(":")
                        ctx["parameters"][k.strip()] = v.strip().strip('"')
                    continue
                else:
                    in_params = False

            # Top-level tag extractions
            for field in ("layer", "upstream_system", "source_table", "target_table",
                          "target_schema", "sla", "description"):
                if stripped.startswith(f"{field}:"):
                    _, _, v = stripped.partition(":")
                    ctx[field] = v.strip().strip('"')

        # Promote parameter fields to top level if not already set
        for field in ("source_table", "target_table", "source_path",
                      "filename_pattern", "archive_path", "target_schema"):
            if not ctx.get(field) and ctx["parameters"].get(field):
                ctx[field] = ctx["parameters"][field]

        return ctx

    def format_for_prompt(self, context: dict[str, Any]) -> str:
        """Format job context as a readable string for injection into LLM prompts."""
        if not context:
            return "No DAB context available for this job."

        lines = [
            f"Job: {context.get('job_name', 'unknown')}",
            f"Description: {context.get('description', 'N/A')}",
            f"Pipeline layer: {context.get('layer', 'N/A')}",
            f"Upstream system: {context.get('upstream_system', 'N/A')}",
            f"Source table/path: {context.get('source_table') or context.get('source_path', 'N/A')}",
            f"Target table: {context.get('target_table', 'N/A')}",
            f"Target schema: {context.get('target_schema', 'N/A')}",
            f"SLA: {context.get('sla', 'N/A')}",
        ]

        if context.get("filename_pattern"):
            lines.append(f"Expected filename pattern: {context['filename_pattern']}")
        if context.get("archive_path"):
            lines.append(f"Archive path: {context['archive_path']}")
        if context.get("parameters"):
            lines.append("Job parameters:")
            for k, v in context["parameters"].items():
                lines.append(f"  {k}: {v}")

        return "\n".join(lines)
